def _trim_summary(text: str) -> str:
    """요약 출력 끝에 전사 내용이 포함된 경우 회의록 끝 마커 이후를 제거"""
    for marker in ("회의녹음요약 앱 자동 생성", "회의록 앱 자동 생성"):
        idx = text.find(marker)
        if idx != -1:
            return text[:idx + len(marker)].strip()
    return text.strip()


