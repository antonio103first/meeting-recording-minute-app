def apply_speaker_names(text: str, speaker_names: dict) -> str:
    """[화자N] → 실제 이름으로 치환"""
    if not text or not speaker_names:
        return text or ""
    for num, name in speaker_names.items():
        if name and name.strip():
            text = text.replace(f"[화자{num}]", f"[{name}]")
    return text


